export function getPostBySlug(slug) {
  return POSTS.find((post) => post.slug === slug);
}

export function getPostSlugs() {
  return POSTS.map((post) => post.slug);
}

/** Same-category posts first, then the rest — newest of each wins ties. */
export function getRelatedPosts(slug, count = 3) {
  const current = getPostBySlug(slug);
  if (!current) return POSTS.slice(0, count);
  return POSTS.filter((p) => p.slug !== slug && p.category === current.category)
    .concat(POSTS.filter((p) => p.slug !== slug && p.category !== current.category))
    .slice(0, count);
}

/** Previous / next article in publication order, for the article footer nav. */
export function getAdjacentPosts(slug) {
  const index = POSTS.findIndex((post) => post.slug === slug);
  if (index < 0) return { previous: null, next: null };
  return {
    previous: index > 0 ? POSTS[index - 1] : null,
    next: index < POSTS.length - 1 ? POSTS[index + 1] : null,
  };
}

